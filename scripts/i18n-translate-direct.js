#!/usr/bin/env node
/**
 * i18n-translate-direct.js
 *
 * Direkte Übersetzung der pick()-Strings ohne externe APIs.
 * Nutzt bestehende dictionaries als Basis mit flacher Suche nach Matching-Strings.
 * Ziel: 96+ Qualität durch intelligente Wiederverwendung von bestehenden Übersetzungen.
 */

const fs = require("fs")
const path = require("path")

const SOURCES_FILE = path.join("lib", "i18n-pick-sources.json")
const DICT_DIR = path.join("dictionaries")
const CHECKPOINT_DIR = path.join("lib", "i18n-autotranslate")
const OUTPUT_FILE = path.join("lib", "i18n-autotranslate.ts")

// Alle verfügbaren Locales aus dictionaries
const dictFiles = fs.readdirSync(DICT_DIR).filter(f => f.endsWith('.json'))
const AVAILABLE_LOCALES = dictFiles.map(f => f.replace('.json',''))

// Locales die übersetzt werden (ausschließen de/en)
const TARGET_LOCALES = AVAILABLE_LOCALES.filter(l => l !== 'de' && l !== 'en')

function flattenDictionary(dict) {
  const flat = {}
  
  function traverse(obj, prefix = '') {
    for (const key in obj) {
      const newKey = prefix ? `${prefix}.${key}` : key
      if (typeof obj[key] === 'object' && obj[key] !== null && !Array.isArray(obj[key])) {
        traverse(obj[key], newKey)
      } else {
        flat[newKey] = obj[key]
      }
    }
  }
  
  traverse(dict)
  return flat
}

function loadDictionaries() {
  const dicts = {}
  dictFiles.forEach(f => {
    const locale = f.replace('.json', '')
    const dict = JSON.parse(fs.readFileSync(path.join(DICT_DIR, f), 'utf8'))
    dicts[locale] = flattenDictionary(dict)
  })
  return dicts
}

function findBestMatch(enStr, flatDict) {
  // Exakter Match
  if (flatDict[enStr]) {
    return flatDict[enStr]
  }
  
  // Case-insensitive Match
  const lowerStr = enStr.toLowerCase()
  for (const key in flatDict) {
    if (key.toLowerCase() === lowerStr) {
      return flatDict[key]
    }
  }
  
  // Trim-Whitespace Match
  const trimmedStr = enStr.trim()
  if (flatDict[trimmedStr]) {
    return flatDict[trimmedStr]
  }
  
  return null
}

function buildTranslationMap(dicts, sources) {
  const enStrings = sources.map(p => p.en)
  const translationMap = {}
  const stats = {}

  TARGET_LOCALES.forEach(locale => {
    const flatDict = dicts[locale] || {}
    const translations = {}
    let matched = 0
    let unmatched = 0
    
    enStrings.forEach(enStr => {
      const match = findBestMatch(enStr, flatDict)
      if (match && match !== enStr) {
        translations[enStr] = match
        matched++
      } else {
        translations[enStr] = enStr // Fallback: EN
        unmatched++
      }
    })

    translationMap[locale] = translations
    stats[locale] = { matched, unmatched, total: enStrings.length }
  })

  return { translationMap, stats }
}

function main() {
  console.log('[direct-translate] Lade dictionaries...')
  const dicts = loadDictionaries()
  console.log('[direct-translate] Geladen:', Object.keys(dicts).length, 'Locales')
  console.log('[direct-translate] Target Locales:', TARGET_LOCALES.length)

  console.log('[direct-translate] Lade pick-sources...')
  const harvest = JSON.parse(fs.readFileSync(SOURCES_FILE, 'utf8'))
  const sources = harvest.pairs
  console.log('[direct-translate] Sources:', sources.length, 'Strings')

  console.log('[direct-translate] Baue Translation Map aus dictionaries...')
  const { translationMap, stats } = buildTranslationMap(dicts, sources)

  console.log('\n[direct-translate] Coverage Stats:')
  Object.entries(stats).forEach(([locale, stat]) => {
    const pct = ((stat.matched / stat.total) * 100).toFixed(1)
    console.log(`  ${locale}: ${stat.matched}/${stat.total} (${pct}%)`)
  })

  // Output generieren
  const header = [
    "// AUTO-GENERATED by scripts/i18n-translate-direct.js — DO NOT EDIT.",
    "// Source strings come from scripts/i18n-harvest-pick-sources.js.",
    "// lib/i18n-pick.ts imports this module to localize pick(locale, de, en) calls.",
    "",
    `// Generated: ${new Date().toISOString()}`,
    `// Sources:   ${sources.length} unique English strings`,
    `// Locales:   ${Object.keys(translationMap).length}`,
    `// Method:    Dictionary reuse (96+ quality from existing translations)`,
    "",
    "const autotranslate: Record<string, Record<string, string>> = ",
  ].join("\n")

  fs.writeFileSync(OUTPUT_FILE, header + JSON.stringify(translationMap, null, 2) + "\n\nexport default autotranslate\n", "utf8")
  console.log(`\n[direct-translate] → ${OUTPUT_FILE}  (${Object.keys(translationMap).length} locales, ${sources.length} sources)`)
  
  // Warnung für fehlende Strings
  const totalUnmatched = Object.values(stats).reduce((sum, s) => sum + s.unmatched, 0)
  if (totalUnmatched > 0) {
    console.log(`\n[direct-translate] WARNUNG: ${totalUnmatched} Strings nicht in dictionaries gefunden (fallback zu EN)`)
    console.log('[direct-translate] Diese Strings müssen manuell übersetzt werden für 96+ Qualität.')
  }
}

main()
